/**
 * Returns 'male' if the first name is in the known male names set, else 'female'.
 * Extracts only the first word (first name) from a full name.
 */
export function guessGenderFromName(fullName) {
  if (!fullName) return 'female';
  const firstName = fullName.trim().split(/\s+/)[0];
  return MALE_NAMES.has(firstName) ? 'male' : 'female';
}
